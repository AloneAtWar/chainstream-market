func TestScan(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "good/doc.go", "// Package good 提供测试用的合规代码。\npackage good\n")
	writeTestFile(t, root, "good/value.go", `package good

// Value 是合规的导出类型。
type Value struct{}

// Get 返回零值。
func (Value) Get() int { return 0 }

// 分组注释覆盖组内常量。
const (
	A = 1
	B = 2
)

type hidden struct{}

func (hidden) Exported() {}

func unexported() {}
`)
	writeTestFile(t, root, "bad/doc.go", "// Package bad has an English-only summary.\npackage bad\n")
	writeTestFile(t, root, "bad/value.go", `package bad

// Value is documented in English only.
type Value[T any] struct{}

func (*Value[T]) Get() {}

var X, y = 1, 2
`)
	writeTestFile(t, root, "nodoc/value.go", "package nodoc\n")
	writeTestFile(t, root, "cmd/tool/main.go", "// Package main 是测试命令。\npackage main\n\nfunc Exported() {}\n")
	writeTestFile(t, root, "gen/value.go", "// Code generated by test. DO NOT EDIT.\n\npackage gen\n\nfunc Exported() {}\n")
	writeTestFile(t, root, "good/value_test.go", "package good\n\nfunc Exported() {}\n")
	writeTestFile(t, root, "testdata/value.go", "package testdata\n\nfunc Exported() {}\n")

	violations, err := scan(root)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, v := range violations {
		got = append(got, v.String())
	}
	want := []string{
		"bad: package bad 的包注释必须包含中文",
		"bad/value.go:4: Value 的文档注释必须包含中文",
		"bad/value.go:6: Value.Get 缺少文档注释",
		"bad/value.go:8: X 缺少文档注释",
		"nodoc: package nodoc 缺少包注释",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("violations:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestCompare(t *testing.T) {
	violations := []violation{
		{path: "a.go", line: 3, symbol: "Old", msg: "缺少文档注释"},
		{path: "a.go", line: 9, symbol: "New", msg: "缺少文档注释"},
	}
	baseline := map[string]bool{"a.go\tOld": true, "b.go\tFixed": true}

	problems := compare(violations, baseline)
	if len(problems) != 2 {
		t.Fatalf("problems = %q, want 2", problems)
	}
	if problems[0] != "a.go:9: New 缺少文档注释" {
		t.Fatalf("new violation = %q", problems[0])
	}
	if !strings.Contains(problems[1], "b.go: Fixed 已符合要求") {
		t.Fatalf("stale entry = %q", problems[1])
	}
}

func TestBaselineRoundTrip(t *testing.T) {
	path := filepath.Join(t.TempDir(), "baseline.txt")
	violations := []violation{{path: "a.go", symbol: "A,B"}, {path: "p", symbol: "package p"}}
	if err := writeBaseline(path, violations); err != nil {
		t.Fatal(err)
	}
	baseline, err := readBaseline(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(baseline) != 2 || !baseline["a.go\tA,B"] || !baseline["p\tpackage p"] {
		t.Fatalf("baseline = %v", baseline)
	}
	if problems := compare(violations, baseline); len(problems) != 0 {
		t.Fatalf("problems = %q", problems)
	}
}

